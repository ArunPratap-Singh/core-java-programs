package pojoPrograming;

public class MobilePhoneDetails {
	
		private String mobileID;
		private String brand;
		private String model;
		private double price;
		private int ram;
		private int storage;
		private String color;
		private String operatingSystem;
		private int batteryCapacity;
		private String camera;
		private String processor;
		private double displaySize;
		private String warranty;
		private String availability;
		private String networkType;
		private String mobileStatus;

		public MobilePhoneDetails() {

		}


		public MobilePhoneDetails(String mobileID, String brand, String model, double price, int ram, int storage, String color, String operatingSystem, int batteryCapacity, String camera, String processor, double displaySize, String warranty, String availability, String networkType, String mobileStatus) {

			this.mobileID = mobileID;
			this.brand = brand;
			this.model = model;
			this.price = price;
			this.ram = ram;
			this.storage = storage;
			this.color = color;
			this.operatingSystem = operatingSystem;
			this.batteryCapacity = batteryCapacity;
			this.camera = camera;
			this.processor = processor;
			this.displaySize = displaySize;
			this.warranty = warranty;
			this.availability = availability;
			this.networkType = networkType;
			this.mobileStatus = mobileStatus;
		}


		public String getMobileID() {

			return mobileID;
		}


		public void setMobileID(String mobileID) {

			this.mobileID = mobileID;
		}


		public String getBrand() {

			return brand;
		}


		public void setBrand(String brand) {

			this.brand = brand;
		}


		public String getModel() {

			return model;
		}


		public void setModel(String model) {

			this.model = model;
		}


		public double getPrice() {

			return price;
		}


		public void setPrice(double price) {

			this.price = price;
		}


		public int getRam() {

			return ram;
		}


		public void setRam(int ram) {

			this.ram = ram;
		}


		public int getStorage() {

			return storage;
		}


		public void setStorage(int storage) {

			this.storage = storage;
		}


		public String getColor() {

			return color;
		}


		public void setColor(String color) {

			this.color = color;
		}


		public String getOperatingSystem() {

			return operatingSystem;
		}


		public void setOperatingSystem(String operatingSystem) {

			this.operatingSystem = operatingSystem;
		}


		public int getBatteryCapacity() {

			return batteryCapacity;
		}


		public void setBatteryCapacity(int batteryCapacity) {

			this.batteryCapacity = batteryCapacity;
		}


		public String getCamera() {

			return camera;
		}


		public void setCamera(String camera) {

			this.camera = camera;
		}


		public String getProcessor() {

			return processor;
		}


		public void setProcessor(String processor) {

			this.processor = processor;
		}


		public double getDisplaySize() {

			return displaySize;
		}


		public void setDisplaySize(double displaySize) {

			this.displaySize = displaySize;
		}


		public String getWarranty() {

			return warranty;
		}


		public void setWarranty(String warranty) {

			this.warranty = warranty;
		}


		public String getAvailability() {

			return availability;
		}


		public void setAvailability(String availability) {

			this.availability = availability;
		}


		public String getNetworkType() {

			return networkType;
		}


		public void setNetworkType(String networkType) {

			this.networkType = networkType;
		}


		public String getMobileStatus() {

			return mobileStatus;
		}


		public void setMobileStatus(String mobileStatus) {

			this.mobileStatus = mobileStatus;
		}

	

}
