package pojoPrograming;

public class LaptopDetails {

	    private int laptopId;
	    private String brand;
	    private String model;
	    private double price;
	    private int ram;
	    private int storage;
	    private String processor;
	    private String operatingSystem;
	    private double screenSize;
	    private String graphicsCard;
	    private String color;
	    private double weight;
	    private String batteryCapacity;
	    private int warranty;
	    private String keyboardType;
	    private String laptopType;

	    public LaptopDetails() {

	    }

	    public LaptopDetails(int laptopId, String brand, String model, double price, int ram, int storage, String processor, String operatingSystem, double screenSize, String graphicsCard, String color, double weight, String batteryCapacity, int warranty, String keyboardType, String laptopType) {

	        this.laptopId = laptopId;
	        this.brand = brand;
	        this.model = model;
	        this.price = price;
	        this.ram = ram;
	        this.storage = storage;
	        this.processor = processor;
	        this.operatingSystem = operatingSystem;
	        this.screenSize = screenSize;
	        this.graphicsCard = graphicsCard;
	        this.color = color;
	        this.weight = weight;
	        this.batteryCapacity = batteryCapacity;
	        this.warranty = warranty;
	        this.keyboardType = keyboardType;
	        this.laptopType = laptopType;
	    }


	    public int getLaptopId() {
	        return laptopId;
	    }

	    public void setLaptopId(int laptopId) {
	        this.laptopId = laptopId;
	    }

	    public String getBrand() {
	        return brand;
	    }

	    public void setBrand(String brand) {
	        this.brand = brand;
	    }

	    public String getModel() {
	        return model;
	    }

	    public void setModel(String model) {
	        this.model = model;
	    }

	    public double getPrice() {
	        return price;
	    }

	    public void setPrice(double price) {
	        this.price = price;
	    }

	    public int getRam() {
	        return ram;
	    }

	    public void setRam(int ram) {
	        this.ram = ram;
	    }

	    public int getStorage() {
	        return storage;
	    }

	    public void setStorage(int storage) {
	        this.storage = storage;
	    }

	    public String getProcessor() {
	        return processor;
	    }

	    public void setProcessor(String processor) {
	        this.processor = processor;
	    }

	    public String getOperatingSystem() {
	        return operatingSystem;
	    }

	    public void setOperatingSystem(String operatingSystem) {
	        this.operatingSystem = operatingSystem;
	    }

	    public double getScreenSize() {
	        return screenSize;
	    }

	    public void setScreenSize(double screenSize) {
	        this.screenSize = screenSize;
	    }

	    public String getGraphicsCard() {
	        return graphicsCard;
	    }

	    public void setGraphicsCard(String graphicsCard) {
	        this.graphicsCard = graphicsCard;
	    }

	    public String getColor() {
	        return color;
	    }

	    public void setColor(String color) {
	        this.color = color;
	    }

	    public double getWeight() {
	        return weight;
	    }

	    public void setWeight(double weight) {
	        this.weight = weight;
	    }

	    public String getBatteryCapacity() {
	        return batteryCapacity;
	    }

	    public void setBatteryCapacity(String batteryCapacity) {
	        this.batteryCapacity = batteryCapacity;
	    }

	    public int getWarranty() {
	        return warranty;
	    }

	    public void setWarranty(int warranty) {
	        this.warranty = warranty;
	    }

	    public String getKeyboardType() {
	        return keyboardType;
	    }

	    public void setKeyboardType(String keyboardType) {
	        this.keyboardType = keyboardType;
	    }

	    public String getLaptopType() {
	        return laptopType;
	    }

	    public void setLaptopType(String laptopType) {
	        this.laptopType = laptopType;
	    }

	

}
