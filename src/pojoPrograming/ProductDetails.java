package pojoPrograming;

public class ProductDetails {
	
		private String productID;
		private String productName;
		private double price;
		private int quantity;
		private String category;
		private String brand;
		private String description;
		private double discount;
		private double rating;
		private String manufacturer;
		private String warranty;
		private String stockStatus;
		private String color;
		private double weight;
		private String productStatus;

		public ProductDetails() {

		}


		public ProductDetails(String productID, String productName, double price, int quantity, String category, String brand, String description, double discount, double rating, String manufacturer, String warranty, String stockStatus, String color, double weight, String productStatus) {

			this.productID = productID;
			this.productName = productName;
			this.price = price;
			this.quantity = quantity;
			this.category = category;
			this.brand = brand;
			this.description = description;
			this.discount = discount;
			this.rating = rating;
			this.manufacturer = manufacturer;
			this.warranty = warranty;
			this.stockStatus = stockStatus;
			this.color = color;
			this.weight = weight;
			this.productStatus = productStatus;
		}


		public String getProductID() {

			return productID;
		}


		public void setProductID(String productID) {

			this.productID = productID;
		}


		public String getProductName() {

			return productName;
		}


		public void setProductName(String productName) {

			this.productName = productName;
		}


		public double getPrice() {

			return price;
		}


		public void setPrice(double price) {

			this.price = price;
		}


		public int getQuantity() {

			return quantity;
		}


		public void setQuantity(int quantity) {

			this.quantity = quantity;
		}


		public String getCategory() {

			return category;
		}


		public void setCategory(String category) {

			this.category = category;
		}


		public String getBrand() {

			return brand;
		}


		public void setBrand(String brand) {

			this.brand = brand;
		}


		public String getDescription() {

			return description;
		}


		public void setDescription(String description) {

			this.description = description;
		}


		public double getDiscount() {

			return discount;
		}


		public void setDiscount(double discount) {

			this.discount = discount;
		}


		public double getRating() {

			return rating;
		}


		public void setRating(double rating) {

			this.rating = rating;
		}


		public String getManufacturer() {

			return manufacturer;
		}


		public void setManufacturer(String manufacturer) {

			this.manufacturer = manufacturer;
		}


		public String getWarranty() {

			return warranty;
		}


		public void setWarranty(String warranty) {

			this.warranty = warranty;
		}


		public String getStockStatus() {

			return stockStatus;
		}


		public void setStockStatus(String stockStatus) {

			this.stockStatus = stockStatus;
		}

		public String getColor() {

			return color;
		}


		public void setColor(String color) {

			this.color = color;
		}


		public double getWeight() {

			return weight;
		}


		public void setWeight(double weight) {

			this.weight = weight;
		}


		public String getProductStatus() {

			return productStatus;
		}


		public void setProductStatus(String productStatus) {

			this.productStatus = productStatus;
		}

	

}
