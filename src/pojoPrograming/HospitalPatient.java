package pojoPrograming;

public class HospitalPatient {
	
	    private int patientId;
	    private String patientName;
	    private int age;
	    private String gender;
	    private String disease;
	    private String doctorName;
	    private String department;
	    private String hospitalName;
	    private String bloodGroup;
	    private String admissionDate;
	    private String dischargeDate;
	    private String roomNumber;
	    private String phoneNumber;
	    private String address;
	    private String treatment;
	    private String medicine;
	    private double consultationFee;
	    private double totalBill;
	    private String patientStatus;
	    private String emergencyContact;

	    public HospitalPatient() {

	    }

	    public HospitalPatient(int patientId, String patientName, int age, String gender, String disease, String doctorName, String department, String hospitalName, String bloodGroup, String admissionDate, String dischargeDate, String roomNumber, String phoneNumber, String address, String treatment, String medicine, double consultationFee, double totalBill, String patientStatus, String emergencyContact) {

	        this.patientId = patientId;
	        this.patientName = patientName;
	        this.age = age;
	        this.gender = gender;
	        this.disease = disease;
	        this.doctorName = doctorName;
	        this.department = department;
	        this.hospitalName = hospitalName;
	        this.bloodGroup = bloodGroup;
	        this.admissionDate = admissionDate;
	        this.dischargeDate = dischargeDate;
	        this.roomNumber = roomNumber;
	        this.phoneNumber = phoneNumber;
	        this.address = address;
	        this.treatment = treatment;
	        this.medicine = medicine;
	        this.consultationFee = consultationFee;
	        this.totalBill = totalBill;
	        this.patientStatus = patientStatus;
	        this.emergencyContact = emergencyContact;
	    }


	    public int getPatientId() {
	        return patientId;
	    }

	    public void setPatientId(int patientId) {
	        this.patientId = patientId;
	    }

	    public String getPatientName() {
	        return patientName;
	    }

	    public void setPatientName(String patientName) {
	        this.patientName = patientName;
	    }

	    public int getAge() {
	        return age;
	    }

	    public void setAge(int age) {
	        this.age = age;
	    }

	    public String getGender() {
	        return gender;
	    }

	    public void setGender(String gender) {
	        this.gender = gender;
	    }

	    public String getDisease() {
	        return disease;
	    }

	    public void setDisease(String disease) {
	        this.disease = disease;
	    }

	    public String getDoctorName() {
	        return doctorName;
	    }

	    public void setDoctorName(String doctorName) {
	        this.doctorName = doctorName;
	    }

	    public String getDepartment() {
	        return department;
	    }

	    public void setDepartment(String department) {
	        this.department = department;
	    }

	    public String getHospitalName() {
	        return hospitalName;
	    }

	    public void setHospitalName(String hospitalName) {
	        this.hospitalName = hospitalName;
	    }

	    public String getBloodGroup() {
	        return bloodGroup;
	    }

	    public void setBloodGroup(String bloodGroup) {
	        this.bloodGroup = bloodGroup;
	    }

	    public String getAdmissionDate() {
	        return admissionDate;
	    }

	    public void setAdmissionDate(String admissionDate) {
	        this.admissionDate = admissionDate;
	    }

	    public String getDischargeDate() {
	        return dischargeDate;
	    }

	    public void setDischargeDate(String dischargeDate) {
	        this.dischargeDate = dischargeDate;
	    }

	    public String getRoomNumber() {
	        return roomNumber;
	    }

	    public void setRoomNumber(String roomNumber) {
	        this.roomNumber = roomNumber;
	    }

	    public String getPhoneNumber() {
	        return phoneNumber;
	    }

	    public void setPhoneNumber(String phoneNumber) {
	        this.phoneNumber = phoneNumber;
	    }

	    public String getAddress() {
	        return address;
	    }

	    public void setAddress(String address) {
	        this.address = address;
	    }

	    public String getTreatment() {
	        return treatment;
	    }

	    public void setTreatment(String treatment) {
	        this.treatment = treatment;
	    }

	    public String getMedicine() {
	        return medicine;
	    }

	    public void setMedicine(String medicine) {
	        this.medicine = medicine;
	    }

	    public double getConsultationFee() {
	        return consultationFee;
	    }

	    public void setConsultationFee(double consultationFee) {
	        this.consultationFee = consultationFee;
	    }

	    public double getTotalBill() {
	        return totalBill;
	    }

	    public void setTotalBill(double totalBill) {
	        this.totalBill = totalBill;
	    }

	    public String getPatientStatus() {
	        return patientStatus;
	    }

	    public void setPatientStatus(String patientStatus) {
	        this.patientStatus = patientStatus;
	    }

	    public String getEmergencyContact() {
	        return emergencyContact;
	    }

	    public void setEmergencyContact(String emergencyContact) {
	        this.emergencyContact = emergencyContact;
	    }

	

}
