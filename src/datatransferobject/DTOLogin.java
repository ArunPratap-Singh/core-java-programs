package datatransferobject;

public class DTOLogin {
	
	private String id;
	private String pwd;
	
	DTOLogin(){
		
	}
	
	public void setID(String id) {
		this.id = id;
	}
	public String getID() {
		return id;
	}
	public void setPWD(String pwd) {
		this.pwd = pwd;
	}
	public String getPWD() {
		return pwd;
	}

}
